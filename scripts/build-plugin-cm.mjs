// Resolve every import from the app's installed, locked dependency graph.
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const app = new URL('app/', root);
const require = createRequire(new URL('package.json', app));
const { build } = require('esbuild'); // Already a transitive Vite dependency.
const lock = JSON.parse(await readFile(new URL('package-lock.json', app), 'utf8'));
const packages = ['@codemirror/autocomplete', '@codemirror/commands', '@codemirror/language', '@codemirror/lint', '@codemirror/search', '@codemirror/state', '@codemirror/view', '@codemirror/lang-markdown', '@lezer/common', '@lezer/highlight', '@lezer/lr', '@lezer/markdown'];
const lockedPackages = Object.keys(lock.packages).filter(path => /^node_modules\/@(codemirror|lezer)\/[^/]+$/.test(path)).map(path => path.slice('node_modules/'.length));
const versions = Object.fromEntries(lockedPackages.map(name => [name, lock.packages[`node_modules/${name}`].version]));
const resolved = new Map();
for (const name of lockedPackages) {
  const manifest = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, app), 'utf8'));
  if (manifest.version !== versions[name]) throw new Error(`${name}: installed version differs from app lockfile; run npm ci`);
  resolved.set(name, fileURLToPath(new URL(`node_modules/${name}/${manifest.module}`, app)));
}
const result = await build({ entryPoints: [fileURLToPath(new URL('core/plugin-runtime/cm6-entry.js', root))], bundle: true,
  format: 'iife', platform: 'browser', target: 'es2022', minify: true, write: false,
  nodePaths: [fileURLToPath(new URL('node_modules', app))], metafile: true,
  define: { PAPERLOOM_CM_VERSIONS: JSON.stringify(versions) },
  plugins: [{ name: 'app-cm-singletons', setup(builder) {
    builder.onResolve({ filter: /^@(codemirror|lezer)\/[^/]+$/ }, args => {
      const path = resolved.get(args.path);
      if (!path) throw new Error(`Unlisted CM dependency: ${args.path}`);
      return { path };
    });
  } }] });
for (const name of lockedPackages) {
  const copies = Object.keys(result.metafile.inputs).filter(path => path.endsWith(`${name}/dist/index.js`));
  if (copies.length > 1 || (packages.includes(name) && copies.length !== 1)) throw new Error(`${name}: expected one resolved instance, got ${copies.length}`);
}
const output = `// Generated by scripts/build-plugin-cm.mjs; rebuild after dependency updates.\n// package-versions: ${JSON.stringify(versions)}\n${result.outputFiles[0].text}`;
await writeFile(new URL('core/plugin-runtime/cm6.js', root), output);
console.log(`cm6.js: ${Buffer.byteLength(output)} bytes`);
